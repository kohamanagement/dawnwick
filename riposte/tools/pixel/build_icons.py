# Builds src/ui/pxicons.ts (sprite sheet as a data URI + glyph map) from the icon modules.
#   python3 tools/pixel/build_icons.py            -> writes src/ui/pxicons.ts
#   python3 tools/pixel/build_icons.py --sheet X  -> also writes a labelled contact sheet PNG to X
import base64, io, json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from PIL import Image, ImageDraw
from pxlib import ICONS, EMOJI, N
import icons_nature, icons_objects, icons_creatures, icons_ui  # noqa: F401  (register icons)

CELL = N + 2   # 1px clear gutter round each icon so scaled sprites never bleed
names = list(ICONS)
cols = 16
rows = (len(names) + cols - 1) // cols
sheet = Image.new('RGBA', (cols * CELL, rows * CELL), (0, 0, 0, 0))
for i, n in enumerate(names):
    sheet.paste(ICONS[n].image(), ((i % cols) * CELL + 1, (i // cols) * CELL + 1))
buf = io.BytesIO()
sheet.save(buf, 'PNG', optimize=True)
b64 = base64.b64encode(buf.getvalue()).decode()

root = os.path.join(os.path.dirname(__file__), '..', '..')
out = os.path.join(root, 'src', 'ui', 'pxicons.ts')
idx = {n: i for i, n in enumerate(names)}
with open(out, 'w', encoding='utf8') as f:
    f.write('// Generated by tools/pixel/build_icons.py. Do not edit by hand: edit the icon grids and rebuild.\n')
    f.write(f'export const PX_COLS = {cols};\nexport const PX_ROWS = {rows};\n')
    f.write(f'export const PX_SHEET = \'data:image/png;base64,{b64}\';\n')
    f.write('/** Icon name -> cell index in the sheet. */\n')
    f.write('export const PX_INDEX: Record<string, number> = ' + json.dumps(idx, ensure_ascii=False) + ';\n')
    f.write('/** Glyph (emoji or symbol, as written in the data) -> icon name. */\n')
    f.write('export const PX_GLYPH: Record<string, string> = ' + json.dumps(EMOJI, ensure_ascii=False) + ';\n')
print(f'{len(names)} icons, {len(EMOJI)} glyphs, sheet {sheet.size}, {len(buf.getvalue())} bytes PNG')

if '--sheet' in sys.argv:
    path = sys.argv[sys.argv.index('--sheet') + 1]
    S = 4; C = 8
    w = C * (N * S + 70)
    h = ((len(names) + C - 1) // C) * (N * S + 18)
    im = Image.new('RGBA', (w, h), (27, 51, 38, 255))
    d = ImageDraw.Draw(im)
    for i, n in enumerate(names):
        x, y = (i % C) * (N * S + 70), (i // C) * (N * S + 18)
        im.paste(ICONS[n].image().resize((N * S, N * S), Image.NEAREST), (x + 4, y + 4), ICONS[n].image().resize((N * S, N * S), Image.NEAREST))
        d.text((x + N * S + 8, y + 24), n, fill=(239, 226, 198, 255))
    im.save(path)
