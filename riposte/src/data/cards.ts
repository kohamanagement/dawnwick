/** Cards that can be offered to a character as rewards (respecting unlock level). */
export function rewardPool(ch: string, level = 99, rarity?: string, owned?: string[]): string[] {
  return C.filter((c) =>
    (CHAR_FACTIONS[ch].includes(c.faction) || (!!c.faction2 && CHAR_FACTIONS[ch].includes(c.faction2))) && !c.evolved
    && (['common', 'uncommon', 'rare'].includes(c.rarity) || (c.rarity === 'legendary' && !!owned?.includes(c.id)))
    && (c.unlock ?? 0) <= level && (!rarity || c.rarity === rarity)).map((c) => c.id);
}

